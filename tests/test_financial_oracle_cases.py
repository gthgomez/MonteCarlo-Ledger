"""Independent hand-derived debt and settlement oracles.

Expected dates and cents live in ``testdata/oracle/debt-settlement-oracle.json``.
They were calculated from the schedule, not generated by the engine under test.
Run against the real SQLite restore path so the Web snapshot, persistence and
forecast adapter are exercised together.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from monte_carlo_ledger import db_manager, scenario, sync
from monte_carlo_ledger.contract import event_rows, run_scenario

REPO_ROOT = Path(__file__).resolve().parents[1]
FIXTURE = REPO_ROOT / "testdata" / "oracle" / "debt-settlement-oracle.json"
DOC = json.loads(FIXTURE.read_text(encoding="utf-8"))


@pytest.mark.parametrize("case", DOC["cases"], ids=[case["id"] for case in DOC["cases"]])
def test_hand_derived_debt_and_settlement_oracle(case, tmp_path, monkeypatch):
    monkeypatch.setattr(db_manager, "DB_PATH", str(tmp_path / "oracle.db"))
    db_manager.init_db()
    sync.restore_ledger_snapshot(case["snapshot"])

    simulation = dict(DOC["simulation"])
    simulation.update(case.get("simulation_overrides", {}))
    built = scenario.build_scenario(
        case["as_of"],
        case["horizon_days"],
        include_simulation=simulation,
        read_only=True,
    )
    rows = [
        [event["date"], event["amount"], event.get("name", "")]
        for event in event_rows(built)
        if event["type"] != "income"
    ]
    assert rows == case["expected"]["cash_events"]

    result = run_scenario(built)
    expected = case["expected"]
    assert result["risk"]["safe_to_spend_cents"] == expected["safe_to_spend_cents"]
    assert result["forecast"]["minimum_balance_cents"] == expected["minimum_balance_cents"]
    assert result["forecast"]["ending_balance_cents"] == expected["ending_balance_cents"]
    assert (
        result["risk"]["negative_balance_probability_ppm"]
        == expected["negative_balance_probability_ppm"]
    )
